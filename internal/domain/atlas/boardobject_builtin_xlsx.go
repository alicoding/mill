package atlas

import "encoding/base64"

// seedSampleWorkbookXLSX is a real, small .xlsx workbook (one sheet, a
// bold header row and a formula column) -- proof that the "sheet"
// board object kind's binary door (goal 0365 S1's atlas_xlsx_read_range/
// atlas_xlsx_edit_cells) has a seeded subject to read and edit, the
// same way seedSampleSheetCSV proves the CSV door. Stored base64 since
// a real .xlsx is a zip archive (binary), never printable Go source
// text the way the CSV/PDF/XML seed assets above are; decoded once at
// package init into the same plain content string
// BuiltInBoardObjectAsset returns for every other asset key.
var seedSampleWorkbookXLSX = mustDecodeBase64Seed(seedSampleWorkbookXLSXBase64)

func mustDecodeBase64Seed(encoded string) string {
	decoded, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		panic("boardobject_builtin_xlsx: seedSampleWorkbookXLSXBase64 does not decode: " + err.Error())
	}
	return string(decoded)
}

